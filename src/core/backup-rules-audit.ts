import type { Finding } from "./types.ts"

export const SENSITIVE_BACKUP_PATHS = [
  "shared_prefs",
  "sharedpref",
  "databases",
  "database",
  "token",
  "secret",
  "credential",
  "key",
] as const

export interface BackupPolicyOptions {
  backupDisabled: boolean
  hasFullBackupContent: boolean
  hasDataExtractionRules: boolean
  evidence?: string
}

export function auditBackupPolicy(options: BackupPolicyOptions): Finding[] {
  if (options.backupDisabled || options.hasFullBackupContent || options.hasDataExtractionRules) return []
  return [{
    severity: "medium",
    code: "BACKUP_NO_EXCLUSION_RULES",
    title: "????????????",
    detail:
      "????allowBackup ??? false????? fullBackupContent / dataExtractionRules????????????(D2D)???????????shared_prefs ???????????????????????",
    recommendation: "? allowBackup=false??? dataExtractionRules?Android 12+?? fullBackupContent ????????/???",
    ...(options.evidence ? { evidence: options.evidence } : {}),
  }]
}

export function auditBackupRulesXml(xml: string, evidence: string): Finding[] {
  const hasExclude = /<exclude\b/.test(xml)
  const excludesSensitive = SENSITIVE_BACKUP_PATHS.some((token) => xml.toLowerCase().includes(token))
  if (hasExclude && excludesSensitive) return []
  return [{
    severity: "low",
    code: "BACKUP_SENSITIVE_NOT_EXCLUDED",
    title: "?????????????",
    detail:
      `???????? ${evidence} ????? shared_prefs/databases/token ?????? <exclude>?????????????????????/?????????????????`,
    recommendation: "??????? shared_prefs?databases ?????/??????? <exclude> ???",
    evidence,
  }]
}
